def verification_guide(settings: dict) -> str:
    level = settings.get("verification_level", DEFAULT_VERIFICATION_LEVEL)
    if level not in VERIFICATION_LEVELS:
        level = DEFAULT_VERIFICATION_LEVEL
    return (
        f"\n[현재 검증 수준: {VERIFICATION_LEVELS[level]} ({level})]\n"
        "검증 범위·계획의 상세도·테스트 도구 제작은 이 설정을 따릅니다. "
        "모드나 이전 세션의 일반적인 '엄격한 검증/AC별 표' 지시보다 현재 설정이 우선합니다.\n"
        + _GUIDES[level] + "\n"
        "어떤 수준에서도 핵심 동작을 모의하거나 무조건 성공하는 명령으로 통과시키지 마세요. "
        "합의 계획에는 실제 확인에 쓰는 test_command 한 줄을 포함하고, 실행 결과와 확인하지 못한 범위를 짧게 보고하세요. "
        "이미 합의한 명령·파일 범위와 명시적 사용자 검증 요구는 유지하세요. "
        "기존 합의의 검증 범위를 줄이려면 새 계획으로 재합의하세요."
    )
